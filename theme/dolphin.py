#!/usr/bin/env python3
"""Write a KDE color scheme from a theme palette. Usage: dolphin.py <theme.js>

Dolphin has its own KColorSchemeManager, so it needs no Qt platform theme. It
loads the scheme named in dolphinrc ([UiSettings] ColorScheme, see switch.sh)
from ~/.local/share/color-schemes. The scheme is read at startup only.
"""
import re, sys, os

src = open(sys.argv[1]).read()
c = dict(re.findall(r'(\w+):\s*"(#[0-9a-fA-F]{6})"', src))


def rgb(name):
    h = c[name]
    return ",".join(str(int(h[i:i + 2], 16)) for i in (1, 3, 5))


def group(name, bg, alt, fg="foreground", inactive="foregroundAlt"):
    return f"""[Colors:{name}]
BackgroundNormal={rgb(bg)}
BackgroundAlternate={rgb(alt)}
ForegroundNormal={rgb(fg)}
ForegroundInactive={rgb(inactive)}
ForegroundActive={rgb('accent')}
ForegroundLink={rgb('blue')}
ForegroundVisited={rgb('purple')}
ForegroundNegative={rgb('red')}
ForegroundNeutral={rgb('yellow')}
ForegroundPositive={rgb('green')}
DecorationFocus={rgb('accent')}
DecorationHover={rgb('accent')}
"""


scheme = "\n".join([
    "# Generated by theme/dolphin.py. Edits are overwritten on theme switch.\n"
    "[General]\nName=Quickshell\nColorScheme=Quickshell\n",
    group("View", "background", "backgroundAlt"),
    group("Window", "backgroundAlt", "background"),
    group("Header", "backgroundAlt", "background"),
    group("Button", "border", "backgroundAlt"),
    group("Tooltip", "backgroundAlt", "background"),
    group("Complementary", "backgroundAlt", "background"),
    group("Selection", "accent", "accent", "background", "background"),
])

path = os.path.expanduser("~/.local/share/color-schemes/Quickshell.colors")
os.makedirs(os.path.dirname(path), exist_ok=True)
with open(path, "w") as f:
    f.write(scheme)
